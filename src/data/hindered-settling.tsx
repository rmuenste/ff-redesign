const cloudColors: Record<HinderedCloudId, string> = {
  n20: "#5fb8ff",
  n40: "#f5b84b",
  n80: "#7bd88f",
  n120: "#ef6f6c"
};

function source(metric: string, file: string, kind: PlotSource["kind"]): PlotSource {
  return { kind, asset: { path: benchmarkAssetPath("hindered-settling", `plots/${metric}/${file}.json`) } };
}

function cloudGroup(metric: string, size: number, kind: PlotSource["kind"]): SeriesGroup {
  const id = `n${size}` as HinderedCloudId;
  return {
    id,
    label: `N = ${size}`,
    kind: "code",
    color: cloudColors[id],
    source: source(metric, id, kind),
    variantStrategy: { kind: "single-trace" }
  };
}

function referenceGroup(
  metric: string,
  id: string,
  label: string,
  kind: PlotSource["kind"],
  color: string
): SeriesGroup {
  return {
    id,
    label,
    kind: "reference",
    color,
    source: source(metric, id, kind),
    variantStrategy: { kind: "single-trace" }
  };
}

