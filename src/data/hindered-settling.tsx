/** Swarm Reynolds number from the plateau velocity: Re = U d / nu, d = 1. */
export const hinderedViscosity = 0.0047;

export function swarmReynolds(u: number) {
  return u / hinderedViscosity;
}

/**
 * Swarm Reynolds range across the ladder, taken over the seed mean at each rung
 * rather than over individual runs — a single seed is not a rung of the ladder.
 */
export const hinderedReynoldsRange = (() => {
  const perRung = hinderedCloudSizes.map(size => {
    const rows = (generated.ladder.confined as HinderedLadderRow[]).filter(row => row.n === size);
    return swarmReynolds(rows.reduce((sum, row) => sum + row.u, 0) / rows.length);
  });
  return { min: Math.min(...perRung), max: Math.max(...perRung) };
})();

